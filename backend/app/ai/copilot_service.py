import time

from google import genai
from google.genai import errors

from app.core.config import settings


class CopilotService:
    """
    ForgeTwin AI Operations Copilot.

    The Copilot is evidence-grounded:
    sensor/ML/maintenance results are generated by the
    ForgeTwin backend, while Gemini is responsible for
    explaining those results to the operator.
    """

    def __init__(self):
        self.client = genai.Client(
            api_key=settings.gemini_api_key
        )

        # Use the model configured in .env.
        #
        # Example:
        # GEMINI_MODEL=gemini-3.8-flash
        #
        # We intentionally avoid a large fallback chain because
        # repeated fallback requests can consume API quota and
        # may target unavailable or deprecated models.
        self.model = settings.gemini_model

        # Keep retries conservative so one operator request
        # does not generate unnecessary API traffic.
        self.max_retries = 1
        self.retry_delay_seconds = 2

    def _build_system_instruction(self) -> str:
        return """
You are ForgeTwin AI Operations Copilot.

You assist manufacturing plant operators by explaining
machine health, telemetry, anomalies, maintenance risk,
incidents, production conditions, and energy-related
observations.

IMPORTANT RULES:

1. Use only the operational evidence supplied by ForgeTwin.
2. Never invent sensor values, incidents, timestamps,
   machine conditions, or maintenance history.
3. Clearly distinguish measured telemetry from ML-derived
   anomaly or risk assessments.
4. Do not claim that a machine will definitely fail.
5. Predictive maintenance results are risk assessments,
   not guaranteed failure predictions.
6. Keep the operator as the final decision-maker.
7. Do not claim that the AI controls or automatically
   repairs the factory.
8. When explaining an abnormal condition, identify the
   relevant telemetry evidence.
9. Prefer concise, operationally useful answers.
10. If the evidence is insufficient to answer a question,
    explicitly say that the available evidence is insufficient.

When appropriate, structure the answer as:

Assessment
- Current condition.

Evidence
- Relevant measured values or ML findings.

Recommended action
- Practical next step based on the supplied maintenance
  assessment.

Do not fabricate information outside the supplied evidence.
"""

    def _build_evidence_context(
        self,
        operations_summary: dict,
    ) -> str:
        return f"""
FORGETWIN PLANT OPERATIONAL EVIDENCE

The following information comes directly from the
ForgeTwin Operations Summary.

Treat these values as authoritative for this request.

{operations_summary}
"""

    def _generate_response(
        self,
        prompt: str,
        system_instruction: str,
    ):
        return self.client.models.generate_content(
            model=self.model,
            contents=prompt,
            config={
                "system_instruction": system_instruction,
                "temperature": 0.2,
            },
        )

    def ask(
        self,
        question: str,
        operations_summary: dict,
    ) -> str:

        system_instruction = self._build_system_instruction()

        evidence_context = self._build_evidence_context(
            operations_summary
        )

        prompt = f"""
{evidence_context}

OPERATOR QUESTION:

{question}

Answer the operator using only the supplied
ForgeTwin operational evidence.
"""

        last_error = None

        for attempt in range(self.max_retries):

            try:
                response = self._generate_response(
                    prompt=prompt,
                    system_instruction=system_instruction,
                )

                if not response.text:
                    return (
                        "The Copilot could not generate a "
                        "response from the available plant evidence."
                    )

                return response.text.strip()

            except errors.ServerError as exc:
                last_error = exc

                print(
                    f"[Copilot] Gemini server error "
                    f"using {self.model} "
                    f"(attempt {attempt + 1}/"
                    f"{self.max_retries}): {exc}"
                )

                if attempt < self.max_retries - 1:
                    time.sleep(self.retry_delay_seconds)

            except errors.ClientError as exc:
                last_error = exc

                print(
                    f"[Copilot] Gemini client error "
                    f"using {self.model}: {exc}"
                )

                break

            except Exception as exc:
                last_error = exc

                print(
                    f"[Copilot] Unexpected error "
                    f"using {self.model}: {exc}"
                )

                break

        raise RuntimeError(
            f"The configured Gemini model "
            f"'{self.model}' is currently unavailable. "
            "Please check the Gemini API quota, model availability, "
            "and API configuration."
        ) from last_error